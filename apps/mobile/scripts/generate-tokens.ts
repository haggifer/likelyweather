import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { parseCssTokens } from '../src/theme/css-tokens'

const CSS_FILE = path.resolve(import.meta.dirname, '../../web/src/app/globals.css')
const OUT_FILE = path.resolve(import.meta.dirname, '../src/theme/tokens.ts')

const { light, dark, radius } = parseCssTokens(readFileSync(CSS_FILE, 'utf8'))

const source = `// Generated by \`pnpm --filter @fa/mobile tokens\` from apps/web/src/app/globals.css. Do not edit.
export const LIGHT = ${JSON.stringify(light, null, 4)}

export const DARK: Record<keyof typeof LIGHT, string> = ${JSON.stringify(dark, null, 4)}

export const RADIUS = ${radius}
`

writeFileSync(OUT_FILE, source)
